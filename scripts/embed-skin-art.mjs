#!/usr/bin/env node
/**
 * Regenerate src/client/art.ts from the committed webp assets as base64 data
 * URIs. The client bundle must not depend on remote or disk runtime assets,
 * so every background layer is inlined at build-input time.
 *
 * Source chain (do not break):
 *   assets/bg-light-source.png  (Dreamy Blue QWEN Blossom Portrait, user-provided AI art)
 *   assets/bg-dark-source.png   (Moonlit Pavilion Dreamscape, user-provided AI art)
 *     -> assets/bg-{light,dark}.webp   (sharp, quality 80, original 1672x941)
 *     -> src/client/art.ts             (this script)
 *
 * Usage: node scripts/embed-skin-art.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))

const LAYERS = [
  ['QWEN_BLOSSOM_LIGHT_ART', 'assets/bg-light.webp'],
  ['QWEN_BLOSSOM_DARK_ART', 'assets/bg-dark.webp'],
]

const header = [
  '/**',
  ' * Generated by scripts/embed-skin-art.mjs — do not edit by hand.',
  ' * Light: Dreamy Blue QWEN Blossom Portrait; Dark: Moonlit Pavilion Dreamscape.',
  ' * Artwork: user-provided AI-generated images (see NOTICE).',
  ' */',
  '',
]

const lines = [...header]
for (const [name, rel] of LAYERS) {
  const buffer = await readFile(resolve(root, rel))
  lines.push(`export const ${name} = 'data:image/webp;base64,${buffer.toString('base64')}';`)
  lines.push('')
  console.log(`${name}: ${rel} ${buffer.byteLength} bytes -> ${(buffer.byteLength * 4 / 3) | 0} base64 chars`)
}

const target = resolve(root, 'src/client/art.ts')
await writeFile(target, lines.join('\n'), 'utf8')
console.log(`written ${target}`)
